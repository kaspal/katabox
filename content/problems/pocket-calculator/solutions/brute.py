import ast


def evaluate(expression: str) -> int:
    # Obviously correct: Python's own parser and arithmetic for + - * and parentheses
    # (validate.py allows nothing else), evaluated by walking the syntax tree.
    def walk(node):
        if isinstance(node, ast.Expression):
            return walk(node.body)
        if isinstance(node, ast.Constant) and type(node.value) is int:
            return node.value
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return -walk(node.operand)
        if isinstance(node, ast.BinOp):
            a, b = walk(node.left), walk(node.right)
            if isinstance(node.op, ast.Add):
                return a + b
            if isinstance(node.op, ast.Sub):
                return a - b
            if isinstance(node.op, ast.Mult):
                return a * b
        raise ValueError("unexpected expression")

    return walk(ast.parse(expression.strip(), mode="eval"))
