//! The complexity profiler's calibration set (ADR 0024): known solutions, profiled in the
//! Windows sandbox, must get the right class at least 85% of the time, each run in under
//! 15 s. Needs the dev sandbox root with the toolchains:
//!
//! ```text
//! pwsh scripts/fetch-toolchains.ps1
//! cargo test -p kb-judge --test complexity_windows -- --nocapture
//! ```
#![cfg(windows)]

use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use kb_core::Language;
use kb_core::profile::ComplexityClass::{self, *};
use kb_judge::{JudgeEnv, Problem};
use kb_runner::ROOT_MARKER;
use serde_json::{Map, Value};

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn env() -> JudgeEnv {
    let root = std::env::var_os("KB_TEST_ROOT")
        .map(PathBuf::from)
        .unwrap_or_else(|| repo().join("target/katabox"));
    let root = std::path::absolute(root).unwrap();
    assert!(
        root.join(ROOT_MARKER).is_file(),
        "no sandbox root at {}",
        root.display()
    );
    JudgeEnv::dev(root)
}

/// A problem's profile inputs, in increasing n: generated by gen.py in the sandbox (the
/// inputs are not committed) and checked against the hashes in `profile/reference.json`.
fn inputs(dir: &Path, env: &JudgeEnv) -> Vec<(u32, Map<String, Value>)> {
    use sha2::{Digest, Sha256};
    let reference: Value =
        serde_json::from_str(&std::fs::read_to_string(dir.join("profile/reference.json")).unwrap())
            .unwrap();
    let sizes: Vec<u32> = reference["sizes"]
        .as_array()
        .unwrap()
        .iter()
        .map(|n| n.as_u64().unwrap() as u32)
        .collect();
    let generator = std::fs::read_to_string(dir.join("gen.py")).unwrap();
    let seed = reference["seed"].as_u64().unwrap();
    let made = kb_judge::generate_sized(
        env,
        &generator,
        seed,
        &sizes,
        kb_judge::ScriptLimits::default(),
    )
    .unwrap();
    for (i, input) in made.iter().enumerate() {
        let text = Value::Object(input.clone()).to_string();
        let hash: String = Sha256::digest(text.as_bytes())
            .iter()
            .map(|b| format!("{b:02x}"))
            .collect();
        assert_eq!(
            Some(hash.as_str()),
            reference["sha256"][i].as_str(),
            "{}",
            dir.display()
        );
    }
    sizes.into_iter().zip(made).collect()
}

/// (problem, solution file, language, expected class)
fn calibration_set() -> Vec<(&'static str, &'static str, Language, ComplexityClass)> {
    let problems: [(&str, ComplexityClass, ComplexityClass); 7] = [
        ("two-sum", Linear, Quadratic),
        ("balanced-streaks", Linear, Quadratic),
        ("fewest-hops", Linear, Quadratic),
        ("thermostat-swings", Linear, Quadratic),
        ("queue-swaps", Linearithmic, Quadratic),
        ("shelf-codes", Linearithmic, Quadratic),
        ("path-tiles", Linear, Exponential),
    ];
    let mut set = Vec::new();
    for (id, fast, slow) in problems {
        for lang in [Language::Python, Language::Rust] {
            set.push((id, "ref", lang, fast));
            set.push((id, "naive", lang, slow));
        }
    }
    set
}

#[test]
fn the_fit_names_the_right_class_at_least_85_percent_of_the_time() {
    let env = env();
    let set = calibration_set();
    let mut hits = 0;
    let mut slowest = Duration::ZERO;
    for &(id, file, lang, want) in &set {
        let dir = repo().join("content/problems").join(id);
        let problem = Problem::load(&dir).unwrap();
        let source =
            std::fs::read_to_string(dir.join(format!("solutions/{file}.{}", lang.extension())))
                .unwrap();
        let inputs = inputs(&dir, &env);
        let started = Instant::now();
        let run = kb_judge::profile::profile(
            &problem,
            lang,
            &source,
            &inputs,
            &env,
            kb_judge::profile::BUDGET,
        )
        .unwrap();
        let wall = started.elapsed();
        slowest = slowest.max(wall);
        let points: Vec<(u32, u32)> = run.points.iter().map(|p| (p.n, p.median_us)).collect();
        let estimate = kb_judge::complexity::estimate(&points);
        let got = estimate.as_ref().map(|e| e.class);
        let hit = got == Some(want);
        hits += usize::from(hit);
        println!(
            "{} {id:<18} {file:<5} {:<6} want {:<12} got {:<28} {wall:>6.1?} {points:?} stop {:?}",
            if hit { "ok  " } else { "MISS" },
            lang.id(),
            want.notation(),
            estimate
                .as_ref()
                .map(|e| format!(
                    "{} ({:.2}{})",
                    e.class.notation(),
                    e.confidence,
                    e.close_alternative
                        .map(|c| format!(", or {}", c.notation()))
                        .unwrap_or_default()
                ))
                .unwrap_or_else(|| "-".into()),
            run.stopped
        );
        assert!(
            wall < Duration::from_secs(15),
            "{id} {file} {lang:?} took {wall:?}"
        );
    }
    let rate = hits as f64 / set.len() as f64;
    println!(
        "hit rate {hits}/{} = {:.0}%; slowest run {slowest:.1?}",
        set.len(),
        rate * 100.0
    );
    assert!(rate >= 0.85, "hit rate {rate:.2}");
}

/// Program problems (features-content M4): their samples are run wall times less the
/// startup. A reference is fast, so its startup usually dominates: "unreliable" is the
/// honest answer for it, and counts as a hit, as does the right class. A naive solution
/// must get a reliable estimate of its class. The bar is the same 85%.
#[test]
fn program_profiles_name_the_slow_class_and_never_guess_the_fast_one() {
    let env = env();
    // fertile-plot (R²·C: no single-n class), bus-sync (no size parameter) and
    // signal-decodes (its exponential naive is either too fast to measure or out of time)
    // have no program profile.
    let problems: [(&str, ComplexityClass, ComplexityClass); 6] = [
        ("badge-visits", Linear, Quadratic),
        ("score-ranks", Linearithmic, Quadratic),
        ("packed-labels", Linearithmic, Quadratic),
        ("tide-lows", Linearithmic, Quadratic),
        ("trail-diameter", Linear, Quadratic),
        ("depot-routes", Linearithmic, Quadratic),
    ];
    let mut cases = 0;
    let mut hits = 0;
    let mut slowest = Duration::ZERO;
    for (id, fast, slow) in problems {
        let dir = repo().join("content/problems").join(id);
        let problem = Problem::load(&dir).unwrap();
        let inputs = inputs(&dir, &env);
        for lang in [Language::Python, Language::Rust] {
            for (file, want) in [("ref", fast), ("naive", slow)] {
                let source = std::fs::read_to_string(
                    dir.join(format!("solutions/{file}.{}", lang.extension())),
                )
                .unwrap();
                let started = Instant::now();
                let run = kb_judge::profile::profile(
                    &problem,
                    lang,
                    &source,
                    &inputs,
                    &env,
                    kb_judge::profile::BUDGET,
                )
                .unwrap();
                let wall = started.elapsed();
                slowest = slowest.max(wall);
                let unreliable = kb_judge::profile::program_unreliable(&run.points, run.startup_us);
                let points: Vec<(u32, u32)> =
                    run.points.iter().map(|p| (p.n, p.median_us)).collect();
                let got = if unreliable {
                    None
                } else {
                    kb_judge::complexity::estimate(&kb_judge::profile::program_fit_points(
                        &run.points,
                        run.startup_us,
                    ))
                    .map(|e| e.class)
                };
                let hit = if file == "ref" {
                    got.is_none() || got == Some(want)
                } else {
                    got == Some(want)
                };
                cases += 1;
                hits += usize::from(hit);
                println!(
                    "{} {id:<15} {file:<5} {:<6} want {:<12} got {:<14} startup {:>6} µs {wall:>6.1?} {points:?} stop {:?}",
                    if hit { "ok  " } else { "MISS" },
                    lang.id(),
                    want.notation(),
                    got.map(|c| c.notation().to_string())
                        .unwrap_or_else(|| "unreliable".into()),
                    run.startup_us,
                    run.stopped
                );
                assert!(
                    wall < Duration::from_secs(15),
                    "{id} {file} {lang:?} took {wall:?}"
                );
            }
        }
    }
    let rate = hits as f64 / cases as f64;
    println!(
        "program hit rate {hits}/{cases} = {:.0}%; slowest run {slowest:.1?}",
        rate * 100.0
    );
    assert!(rate >= 0.85, "hit rate {rate:.2}");
}
