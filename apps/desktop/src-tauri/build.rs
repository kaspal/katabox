use std::path::PathBuf;

fn main() {
    // content.db is a bundled resource: build it from content/problems (and the Learn
    // topics in content/learn, ADR 0029) first, so that `pnpm dev`, `tauri build` and a
    // plain `cargo check` all have it (ADR 0011).
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let problems = manifest.join("../../../content/problems");
    let out = manifest.join("resources/content.db");
    println!("cargo:rerun-if-changed={}", problems.display());
    let learn = manifest.join("../../../content/learn");
    println!("cargo:rerun-if-changed={}", learn.display());
    println!(
        "cargo:rerun-if-changed={}",
        manifest.join("../src/learn/tracers").display()
    );
    // The pack's id, version and date (shown on Settings → About).
    println!(
        "cargo:rerun-if-changed={}",
        kb_pack::pack::pack_file_for(&problems).display()
    );
    let version = std::env::var("CARGO_PKG_VERSION").expect("package version");
    if let Err(e) = kb_pack::build_content(&problems, &out, &version) {
        panic!("building {}: {e}", out.display());
    }
    notices(&manifest);
    identifier(&manifest);
    tauri_build::build()
}

/// `KATABOX_IDENTIFIER` = tauri.conf.json's `identifier`, for `--uninstall-cleanup`,
/// which finds the data folders before Tauri starts (one source of truth).
fn identifier(manifest: &std::path::Path) {
    let conf = manifest.join("tauri.conf.json");
    println!("cargo:rerun-if-changed={}", conf.display());
    let text = std::fs::read_to_string(&conf).expect("read tauri.conf.json");
    let key = "\"identifier\"";
    let at = text.find(key).expect("identifier in tauri.conf.json");
    let value = text[at + key.len()..]
        .split('"')
        .nth(1)
        .filter(|v| !v.is_empty())
        .expect("identifier value");
    println!("cargo:rustc-env=KATABOX_IDENTIFIER={value}");
}

/// The first line of the placeholder notices file (kb-app shows "included in release
/// builds" for it; keep in sync with `kb_app::NOTICES_PLACEHOLDER`).
const NOTICES_PLACEHOLDER: &str = "KATABOX_NOTICES_PLACEHOLDER";

/// THIRD_PARTY_NOTICES.txt is a bundled resource generated by `pnpm notices` (ADR 0021).
/// Development builds get a placeholder; a release build refuses to ship one.
fn notices(manifest: &std::path::Path) {
    let path = manifest.join("resources/THIRD_PARTY_NOTICES.txt");
    println!("cargo:rerun-if-changed={}", path.display());
    println!("cargo:rerun-if-env-changed=KATABOX_ALLOW_PLACEHOLDER_NOTICES");
    let placeholder = std::fs::read_to_string(&path)
        .map(|s| s.starts_with(NOTICES_PLACEHOLDER))
        .unwrap_or(true);
    if !placeholder {
        return;
    }
    let release = std::env::var("PROFILE").as_deref() == Ok("release");
    if release && std::env::var_os("KATABOX_ALLOW_PLACEHOLDER_NOTICES").is_none() {
        panic!(
            "{} is missing or a placeholder: run `pnpm notices` before a release build",
            path.display()
        );
    }
    if !path.exists() {
        std::fs::write(
            &path,
            format!(
                "{NOTICES_PLACEHOLDER}\nRun `pnpm notices` to generate the third-party notices.\n"
            ),
        )
        .expect("write the placeholder notices");
    }
}
